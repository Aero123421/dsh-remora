// Copies shared files into hub/ so it builds on its own (the Deploy to
// Cloudflare button only sees that folder):
//   packages/protocol/src/*.ts  -> hub/src/vendor/protocol/  (with a header)
//   assets/remora-*.{svg,png}   -> hub/public/
//   node scripts/vendor-protocol.mjs          write the copies
//   node scripts/vendor-protocol.mjs --check  fail if a copy is stale (CI)
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const header = Buffer.from('// GENERATED by scripts/vendor-protocol.mjs from packages/protocol/src — do not edit here.\n')
const check = process.argv.includes('--check')

const sets = [
  { from: 'packages/protocol/src', to: 'hub/src/vendor/protocol', match: name => name.endsWith('.ts'), prefix: header, exclusive: true },
  { from: 'assets', to: 'hub/public', match: name => /^remora-.*\.(svg|png)$/.test(name), prefix: Buffer.alloc(0), exclusive: false },
]

const stale = []
for (const set of sets) {
  const source = join(repo, set.from), target = join(repo, set.to)
  const names = (await readdir(source)).filter(set.match).sort()
  const expected = new Map(await Promise.all(names.map(async name => [name, Buffer.concat([set.prefix, await readFile(join(source, name))])])))
  if (check) {
    const present = (await readdir(target).catch(() => [])).filter(set.match)
    for (const name of new Set([...names, ...present])) {
      const current = await readFile(join(target, name)).catch(() => undefined)
      const wanted = expected.get(name)
      if (!current || !wanted || !current.equals(wanted)) stale.push(`${set.to}/${name}`)
    }
  } else {
    if (set.exclusive) await rm(target, { recursive: true, force: true })
    await mkdir(target, { recursive: true })
    for (const name of (await readdir(target)).filter(set.match)) if (!expected.has(name)) await rm(join(target, name))
    for (const [name, bytes] of expected) await writeFile(join(target, name), bytes)
    console.log(`copied ${names.length} files to ${set.to}`)
  }
}

if (check) {
  if (stale.length > 0) {
    console.error(`hub/ copies are out of date:\n  ${stale.join('\n  ')}\nRun: pnpm vendor:sync`)
    process.exit(1)
  }
  console.log('hub/ copies are up to date')
}
