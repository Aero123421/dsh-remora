#!/usr/bin/env node
// Turns dist/remora.mjs into a standalone `remora` executable for the platform
// this script runs on, using Node's single executable applications (SEA):
//
//   1. re-bundle dist/remora.mjs as CommonJS (Node 22's SEA entry must be CJS)
//   2. node --experimental-sea-config  → preparation blob
//   3. copy the node binary, inject the blob with postject (pinned 1.0.0-alpha.6)
//   4. macOS: remove the signature before injecting, ad-hoc sign afterwards
//   5. smoke test: `<binary> --version` must print the package version
//
// Usage (from the repo root, after `pnpm build`):
//   node packages/cli/scripts/build-binaries.mjs [--out-dir artifacts/cli] [--node <path>] [--skip-smoke]
//
// Output: <out-dir>/remora-<process.platform>-<process.arch>[.exe]
// (linux-x64, linux-arm64, darwin-x64, darwin-arm64, win32-x64). The last line
// on stdout is the path of the binary; its SHA-256 is printed before it.
// Cross-building is not supported: run it on a native runner per target.
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { chmod, copyFile, mkdir, mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { createRequire } from 'node:module'

const SENTINEL_FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2'
const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(pkgRoot, '../..')

const { values } = parseArgs({
  options: {
    input: { type: 'string', default: join(pkgRoot, 'dist/remora.mjs') },
    'out-dir': { type: 'string', default: join(repoRoot, 'artifacts/cli') },
    node: { type: 'string', default: process.execPath },
    'skip-smoke': { type: 'boolean', default: false },
  },
})

const platform = process.platform
const arch = process.arch
const name = `remora-${platform}-${arch}${platform === 'win32' ? '.exe' : ''}`
const outDir = resolve(values['out-dir'])
const output = join(outDir, name)
const nodeBinary = resolve(values.node)
const manifest = JSON.parse(await readFile(join(pkgRoot, 'package.json'), 'utf8'))

function run(command, args, options = {}) {
  return execFileSync(command, args, { stdio: ['ignore', 'pipe', 'inherit'], encoding: 'utf8', ...options })
}

const nodeVersion = run(nodeBinary, ['--version']).trim()
const [major] = nodeVersion.replace(/^v/, '').split('.').map(Number)
if (major < 22) throw new Error(`Node ${nodeVersion} is too old for SEA builds; use Node 22.19 or later.`)
await stat(values.input).catch(() => { throw new Error(`${values.input} is missing. Run \`pnpm build\` first.`) })

const work = await mkdtemp(join(tmpdir(), 'remora-sea-'))
try {
  // 1. CommonJS entry for the SEA. Everything is already bundled; this only changes the module format.
  const main = join(work, 'remora.cjs')
  await build({
    entryPoints: [values.input],
    outfile: main,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    legalComments: 'none',
    logLevel: 'warning',
  })

  // 2. Preparation blob. Generated by the same Node binary that is embedded.
  const blob = join(work, 'sea-prep.blob')
  const config = join(work, 'sea-config.json')
  await writeFile(config, JSON.stringify({
    main,
    output: blob,
    disableExperimentalSEAWarning: true,
    useSnapshot: false,
    useCodeCache: false,
  }))
  run(nodeBinary, ['--experimental-sea-config', config], { cwd: work })

  // 3. Copy node and inject.
  await mkdir(outDir, { recursive: true })
  await rm(output, { force: true })
  await copyFile(nodeBinary, output)
  await chmod(output, 0o755)
  if (platform === 'darwin') run('codesign', ['--remove-signature', output])
  const require = createRequire(import.meta.url)
  const { inject } = require('postject')
  await inject(output, 'NODE_SEA_BLOB', await readFile(blob), {
    sentinelFuse: SENTINEL_FUSE,
    overwrite: true,
    ...(platform === 'darwin' ? { machoSegmentName: 'NODE_SEA' } : {}),
  })

  // 4. macOS refuses to run arm64 binaries without a signature: ad-hoc sign.
  if (platform === 'darwin') run('codesign', ['--sign', '-', '--force', output])

  // 5. Smoke test.
  if (!values['skip-smoke']) {
    const version = run(output, ['--version'], { env: { ...process.env, REMORA_CONFIG_DIR: work } }).trim()
    if (version !== manifest.version) throw new Error(`smoke test: ${name} --version printed "${version}", expected "${manifest.version}"`)
    run(output, ['help'], { env: { ...process.env, REMORA_CONFIG_DIR: work } })
  }

  const bytes = await readFile(output)
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  console.log(`remora@${manifest.version} ${name}: ${(bytes.length / 1024 / 1024).toFixed(1)} MiB, node ${nodeVersion}`)
  console.log(`${sha256}  ${name}`)
  console.log(output)
} finally {
  await rm(work, { recursive: true, force: true })
}
